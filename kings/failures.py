"""Collect every position where the frozen-king assumption gives the wrong outcome
into kings/results/FAILURES.md:
  1. the small-board sweeps (kings/results/exp_*_diagnosis.jsonl), all exact;
  2. the paper's king groups on 8x8 (kings/results/king_groups_8x8.txt);
  3. the *2 tree and the engine suite (kings/data/), from cached Lichess results.

Run from the project root:  python3 kings/failures.py
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "kings", "results")
SIDE = {"wtm": "White to move", "btm": "Black to move"}
WORD = {"W": "White wins", "L": "Black wins", "D": "draw"}


def main():
    out = ["# Positions where frozen kings give the wrong outcome", "",
           "Generated by `kings/failures.py`. Results are from White's point of view.", ""]
    out += ["## 1. Small-board sweeps (exact; kings/kpsolve)", "",
            "Each row is a pawn component P beside the board's trébuchet (see `kings/experiment.py` for the layout).",
            "\"Escape\" means only king moves reach the real result; \"king refutes\" means every pawn move the",
            "convention counts as winning is refuted by a king move.", "",
            "| Board | P | cylcgt value | Side | Convention | Real | Diagnosis | Real best moves / refutations |",
            "|---|---|---|---|---|---|---|---|"]
    for path in sorted(glob.glob(f"{RES}/exp_*_diagnosis.jsonl")):
        board = os.path.basename(path).split("_")[1]
        for line in open(path):
            c = json.loads(line)
            if "best_moves" in c:
                detail = ", ".join(c["best_moves"])
            else:
                detail = "; ".join(f"{m} → {', '.join(v['refutations'])}" for m, v in c.get("refutations", {}).items())
            short = "escape" if c["diagnosis"].startswith("escape") else (
                "king refutes" if c["diagnosis"].startswith("king refutes") else c["diagnosis"])
            out.append(f"| {board} | {c['P']} | {c['value']} | {SIDE[c['side']]} | {WORD[c['predicted']]} | "
                       f"{WORD[c['real']]} | {short} | {detail} |")
    out += ["", "## 2. The paper's king groups alone on 8×8 (exact; kings/kpsolve)", "",
            "The convention scores a king group as 0: the side to move loses.", "",
            "| Board | Group | Claimed | Side | Real | Moves and their values |", "|---|---|---|---|---|---|"]
    claims = {"Kh5 Pa4 kb4 pa5": ("5.1 trébuchet", "0 (paper, audit)"),
              "Ke6 Pd7 kd8 pe7": ("7.2 king group", "0 (paper; audit: zugzwang under the convention)"),
              "Kg8 Pf7 kf6 pg7": ("7.3 as drawn", "0 (paper; audit: not a zugzwang)"),
              "Kg6 Pf7 kf8 pg7": ("7.3, kings as the audit conjectures", "0 (diagram audit, conjecture)"),
              "Kf5 Pg4 kh4 pg5": ("*2 candidate's trébuchet", "0 (RESULTS.md §1)")}
    board = None
    kg = os.path.join(RES, "king_groups_8x8.txt")
    if os.path.exists(kg):
        for line in open(kg):
            if line.startswith("== "):
                board = line[3:].strip()
                continue
            if "|" not in line or line.startswith("#"):
                continue
            pos, res, *mv = [p.strip() for p in line.split("|")]
            a, b = res.split()
            group, claim = claims[pos[:-4]]
            if board == "flat:8x8" and group.startswith("5.1"):
                continue  # a cylinder pattern
            stm = pos.split()[-2]
            conv = "L" if stm == "w" else "W"
            flag = "" if a == conv else " **(convention wrong)**"
            moves = mv[0][3:] if mv and mv[0].startswith("A: ") else (mv[0] if mv else "")
            out.append(f"| {board} | {group}: {pos[:-4]} | {claim} | {'White' if stm == 'w' else 'Black'} to move | "
                       f"{WORD[a]}{flag} | {moves} |")
    out += ["", "## 3. The *2 tree and the engine suite (Lichess tablebase; kings/data/DATA.md)", "",
            "These are the cases the data extraction attributes to kings (the others are e.p., races and",
            "faster counter-passers). FENs are on the ordinary 8×8 board.", "",
            "| Source | Position | Real vs convention | Mechanism |", "|---|---|---|---|",
            "| *2 terminal | W a5 / B b7 c5 `8/1p6/8/P1p2Kp1/6Pk/8/8/8 w` | White to move draws (Ke4, Ke5); convention: Black wins | the White king gives up g4 and catches the c-pawn |",
            "| *2 node | W a5 c3 / B b7 d5 `8/1p6/8/P2p1Kp1/6Pk/2P5/8/8 w` | White to move draws; convention: White loses | both pawn moves lose, so a king move draws |",
            "| *2 terminal (probable) | W c4 / B a6 d6 `8/8/p2p4/5Kp1/2P3Pk/8/8/8 w` | White to move draws; convention: Black wins | drawing move not recorded; the White king stands in the a-pawn's square |",
            "| suite cgt055 | `8/2p5/2p5/2P2Kp1/6Pk/8/8/8 w` | draw by Ke6 only; convention: White loses | king trades g4 for the queenside pawns |",
            "| suite cgt120 | `8/8/8/3p1Kp1/3P2Pk/2P5/8/8 w` | White wins by Ke5 or Ke6; convention: White loses | king walks to the blockaded d5 pawn |",
            "| suite cgt123 | `8/8/8/2p2Kp1/2P3Pk/1P6/8/8 w` | all five king moves draw; convention: White loses | king trades g4 for a queenside pawn |",
            "| suite cgt262 | `8/8/8/2p3pK/2P2kP1/3P4/8/8 w` | Kg6 draws; convention: White loses | not recorded |",
            "| suite cgt270 | `8/8/8/3p2pK/3P1kP1/2P5/8/8 w` | Kg6 draws; convention: White loses | not recorded |",
            "| *2 terminal (data review; Lichess 8-man category) | W a4 c4 / B b6 d4 `8/8/1p6/5Kp1/P1Pp2Pk/8/8/8 w` | White to move wins by Ke4; convention: Black wins | the king leaves the trébuchet; lower confidence (8-man category, not trusted by realchess by default) |",
            "| *2 node (data review; Lichess 8-man category) | W a5 c5 / B b7 d7 `8/1p1p4/8/P1P2Kp1/6Pk/8/8/8 w` | White to move draws by Kg6 or Kf6; convention: White loses | lower confidence, as above |", "",
            "## 4. The theory's positive control P4 (7×6 cylinder, exact at cap 2)", "",
            "A frozen trébuchet Z_T = Ka4 Pb3 / kc3 pb4 beside one-file tempo contexts (theory/LOOPY.md §6, P4).", "",
            "| Context | Side | Convention | Real | Real move values |", "|---|---|---|---|---|"]
    mv = os.path.join(RES, "theory_P4_cap2_moves.txt")
    if os.path.exists(mv):
        names = {"Pe3 pe5": "H* = Pe3 / pe5", "Pe4 pe5": "H* after 1.e3-e4", "Pe3 pe4": "H0 = Pe3 / pe4"}
        conv = {("Pe3 pe5", "w"): "White wins", ("Pe4 pe5", "b"): "White wins", ("Pe3 pe4", "b"): "White wins"}
        for line in open(mv):
            if "|" not in line:
                continue
            pos, res, moves = [p.strip() for p in line.split("|")]
            ctx = " ".join(pos.split()[4:6])
            stm = pos.split()[-2]
            out.append(f"| {names.get(ctx, ctx)} | {'White' if stm == 'w' else 'Black'} to move | "
                       f"{conv.get((ctx, stm), '?')} | {WORD[res.split()[0]]} | {moves} |")
    out.append("")
    with open(os.path.join(RES, "FAILURES.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {RES}/FAILURES.md ({len(out)} lines)")


if __name__ == "__main__":
    main()
