"""K73: the part of Table B that the 42 positions of K68 VERIFY.md section 5 reach.

Run from the project root:  .venv/bin/python -B -I kings/delegate/out/K70/verify/src/k73_table42.py > kings/delegate/out/K70/verify/TABLE42.md
Uses the move generator and parser of k73_check.py (same directory).
"""
import os
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import k73_check as C  # noqa: E402

NEED = {
    "c2": "b2 b3 c3 d2 d3 e2 e3 e4 e5 e6 f2 f3 f4 f5 f6".split(),
    "c3": "c2 d2 d3 e2 e3 e4 e5 e6 f2 f3 f4 f5 f6".split(),
    "c4": "c2 c3 d2 d3 e2 e3 e4 e5 e6 f2 f3 f4 f5 f6".split(),
}
ENTRY = {
    "c2": {"K": [481, 486], "c3": [475, 480], "c4": [445, 448, 451]},
    "c3": {"K": [475, 480], "c4": [445, 448, 451]},
    "c4": {"K": [445, 448, 451], "c5": [414, 417]},
}


def main():
    rows, order = C.parse_proof(C.PROOF)
    B = rows["B"]
    for r in order:
        r._zone = set(p.wk if r.table == "B" else p.bk for p in C.row_positions(r))

    def locate(nums, p):
        hits = [n for n in nums if C.row_member(B[n], p)]
        assert len(hits) == 1, (nums, p.fen(), hits)
        return hits[0]

    entry_lines = []
    frontier = []
    seen = set()
    reached_sq = defaultdict(set)
    for g, ks in NEED.items():
        for k in ks:
            p = C.Pos(C.sq(k), C.sq("b6"), {C.sq(g)}, {C.sq("b7"), C.sq("c6")}, 0)
            items = []
            for t, q, pr in sorted(C.legal_moves(p), key=lambda x: x[0]):
                n = locate(ENTRY[g][C.reply_class(t)], q)
                items.append(f"{t}→B{n}")
                if q.key() not in seen:
                    seen.add(q.key())
                    frontier.append((n, q))
            entry_lines.append(f"| {g} | {k} | {len(items)} | " + " · ".join(items) + " |")
    # position-level reachability under the table's own strategy
    npos = 0
    while frontier:
        n, p = frontier.pop()
        npos += 1
        r = B[n]
        reached_sq[n].add(p.wk)
        mv = {t: (q, pr) for t, q, pr in C.legal_moves(p)}
        q, promo = mv[r.play]
        if promo:
            continue
        for t, q2, pr in C.legal_moves(q):
            m = locate(r.replies[C.reply_class(t)], q2)
            if q2.key() not in seen:
                seen.add(q2.key())
                frontier.append((m, q2))
    reach_rows = sorted(reached_sq)
    # row-level closure (rows with their full zones, closed under every cited reference)
    closure = set()
    st = sorted({int(x.split("→B")[1]) for ln in entry_lines for x in ln.split("| ")[4].strip(" |").split(" · ")})
    st = list(st)
    while st:
        n = st.pop()
        if n in closure:
            continue
        closure.add(n)
        for c, nums in B[n].replies.items():
            if c != "end":
                st.extend(nums)
    # self-check of the position-restricted sub-table: every reply of a reached position lands in a reached row/square
    bad = 0
    for n in reach_rows:
        r = B[n]
        for wk in reached_sq[n]:
            p = C.Pos(wk, r.king, r.wp, r.bp, 1, r.ep)
            q, promo = {t: (q, pr) for t, q, pr in C.legal_moves(p)}[r.play]
            if promo:
                continue
            for t, q2, pr in C.legal_moves(q):
                m = locate(r.replies[C.reply_class(t)], q2)
                if q2.wk not in reached_sq.get(m, ()):
                    bad += 1
    out = []
    out.append("# TABLE42: the part of Table B used by Proposition 4.25")
    out.append("")
    out.append("K73 referee, 2026-11-25. Generated by `src/k73_table42.py` from `kings/delegate/out/K70/PROOF.md` and the 42")
    out.append("Lemma B positions of `kings/delegate/out/K68/verify/VERIFY.md` §5 (White to move; Black Kb6, pb7, pc6).")
    out.append("Conventions are those of PROOF.md, Table B. CHECKED by program (k73_check.py), not by hand.")
    out.append("")
    out.append(f"- Positions reached under the table's strategy (Black to move, after the 42 starts and every White reply): **{npos}**.")
    out.append(f"- Rows of Table B containing a reached position: **{len(reach_rows)}** of 486.")
    out.append(f"- Rows in the closure of the entry rows under every cited reference (full zones): **{len(closure)}** of 486.")
    out.append(f"- Self-check of the restricted sub-table below (replies of reached positions leaving the reached set): {bad}.")
    out.append("")
    out.append("## Entry rows after each legal White first move")
    out.append("")
    out.append("| γ | White king | moves | White move → entry row |")
    out.append("|---|---|---:|---|")
    out.extend(entry_lines)
    out.append("")
    out.append("## Sub-table (rows with a reached position)")
    out.append("")
    out.append("Zone is PROOF.md's zone; squares of it (after the discards) that the 42 starts never reach are listed in")
    out.append("parentheses. Replies cite only rows of this sub-table (citations of unreached rows are dropped); every reply")
    out.append("from a reached square lands on a reached square of a cited row.")
    head = None
    for n in reach_rows:
        r = B[n]
        h = (r.wp, r.bp)
        if h != head:
            head = h
            wpn = C.nm(tuple(r.wp)[0]) if r.wp else "-"
            bps = [C.nm(x) for x in sorted(r.bp, key=lambda s: (C.F(s), C.R(s)))]
            # keep PROOF.md's heading text
            src = [ln for ln in open(C.PROOF, encoding="utf-8").read().split("\n") if C.HEAD.match(ln)]
            txt = None
            for ln in src:
                m = C.HEAD.match(ln)
                w_, b1, b2 = m.groups()
                if (w_ == wpn) and {x for x in (b1, b2) if x != "-"} == set(bps):
                    txt = ln
                    break
            out.append("")
            out.append(txt)
            out.append("")
            out.append("| # | King | Zone | Play | Replies |")
            out.append("|---:|:---:|:---|:---|:---|")
        miss = sorted(r._zone - reached_sq[n], key=lambda s: (C.F(s), C.R(s)))
        z = r.zone_spec + (" (not reached: " + ",".join(C.nm(s) for s in miss) + ")" if miss else "")
        rep = []
        for c, nums in r.replies.items():
            if c == "end":
                rep.append("end→" + ",".join(nums))
                continue
            keep = [x for x in nums if x in reached_sq]
            if keep:
                rep.append(f"{c}→" + ",".join(map(str, keep)))
        out.append(f"| {n} | {C.nm(r.king)} | {z} | {r.play} | {' '.join(rep)} |")
    out.append("")
    out.append("Rows of Table B not reached: " + ", ".join(str(n) for n in sorted(B) if n not in reached_sq) + ".")
    out.append("Rows outside the full-zone closure: " + ", ".join(str(n) for n in sorted(B) if n not in closure) + ".")
    print("\n".join(out))
    print(f"reached positions {npos}, rows {len(reach_rows)}, closure rows {len(closure)}, bad {bad}", file=sys.stderr)


if __name__ == "__main__":
    main()
