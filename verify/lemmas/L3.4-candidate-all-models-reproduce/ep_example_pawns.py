"""Show, with the project's own cylcgt.pawns (read-only), one contested child:
White plays a2-a4 from W a2 c2 / B b4 d3 (4x8 flat, e.p. on). The model scores the
child +BIG at once, although Black's e.p. capture b4xa3 (generated by pawns.moves
from that child) leaves Black with the only passer.
Run: PYTHONPATH=. .venv/bin/python verify/lemmas/L3.4-candidate-all-models-reproduce/ep_example_pawns.py"""
from cylcgt import cgt, pawns
from cylcgt.pawns import Board, Pos
from lemmas.common import W, reachable, terminal
b = Board(4, 8, False, True)
parent = Pos.parse("W: a2 c2 / B: b4 d3")
root = Pos.parse("W: a2 c2 / B: b7 d7")
print("parent reachable from candidate:", parent in reachable(b, root), " terminal:", terminal(b, parent))
for c in pawns.moves(b, parent, "W"):
    if c.ep and c.ep[1] == (0, 4):
        print("child:", c, " passed W/B:", pawns.passed(b, c, "W"), pawns.passed(b, c, "B"),
              " model score of child:", cgt.show(W(b, c, "count")))
        for g in pawns.moves(b, c, "B"):
            if (0, 4) not in g.white:
                print("   Black e.p. reply:", g, " passed W/B:", pawns.passed(b, g, "W"), pawns.passed(b, g, "B"))
