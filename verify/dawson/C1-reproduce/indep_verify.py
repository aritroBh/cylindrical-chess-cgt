"""Independent verifier for a claimed misere quotient of Dawson's chess (0.137), written for the
C1 adversarial check. Shares NO code with dawson/ (own move rule, own checks).

Input: a pickle {"mult", "P", "phi", "gens"} as written by dawson/quotient.py.
Checks, all exact:
  1. monoid axioms: 0 is the identity, table is commutative, associative (full n^3 check);
  2. Phi is onto: the submonoid generated by Phi(strip h), h in gens, is all of Q;
  3. Q is reduced: no two distinct x, y with P[xz] == P[yz] for every z (Moore refinement);
  4. P[0] is False (empty position is a misere N-position: the player to move has no move, wins);
  5. P-condition: for every y in Q, strip h, option o of h: not (P[y*h] and P[y*o]);
  6. N-condition: for every nonempty position G with Phi(G) not in P, some option of G maps into P.
     Proved by an antichain fixpoint over pairs (x, E) = (Phi(G), {Phi(G') : G' option of G}),
     keeping only inclusion-minimal E per x (the N-condition is upward closed in E and the
     successor maps are monotone in E).
Together 4-6 prove, by induction on positions, that Phi(G) in P iff G is a misere P-position for
every finite sum G of strips of length <= max(gens). With 1-3, Q is the misere quotient.

Move rule (derived from the pin model of Dawson's chess, not from octal digits): a strip of n
untouched files; choosing file i (1..n) removes files i-1, i, i+1 (those that exist), leaving
runs of max(0, i-2) and max(0, n-i-1) files.

Run from project root:
  PYTHONPATH=. .venv/bin/python verify/dawson/C1-reproduce/indep_verify.py <pkl>
"""
import pickle
import sys
import time


def strip_options(n):
    out = set()
    for i in range(1, n + 1):
        a, b = max(0, i - 2), max(0, n - i - 1)
        out.add(tuple(sorted(x for x in (a, b) if x > 0)))
    return out


def main(pkl):
    t0 = time.time()
    d = pickle.load(open(pkl, "rb"))
    mult, P, phi, gens = d["mult"], [bool(p) for p in d["P"]], dict(d["phi"]), list(d["gens"])
    N = len(mult)
    H = max(gens)
    print(f"{pkl}: |Q| = {N}, |P| = {sum(P)}, gens = {gens}")
    # Phi of every strip length 1..H (strip 2 is not a generator: same game tree as strip 1)
    assert 2 not in phi
    assert sorted(phi) == [h for h in range(1, H + 1) if h != 2], sorted(phi)
    ph = dict(phi)
    ph[2] = phi[1]
    # sanity: strip 2 and strip 1 have identical game trees
    assert strip_options(1) == {()} and strip_options(2) == {()}

    # 1. monoid axioms
    assert all(len(r) == N for r in mult)
    assert all(mult[0][x] == x and mult[x][0] == x for x in range(N)), "identity"
    assert all(mult[x][y] == mult[y][x] for x in range(N) for y in range(x, N)), "commutative"
    # associativity by Light's test (valid because Q is generated by the Phi(h), checked in 2;
    # the onto check is done first, below, and asserted before this result is used)
    seen = {0}
    fr = [0]
    while fr:
        nf = []
        for q in fr:
            for h in gens:
                y = mult[q][ph[h]]
                if y not in seen:
                    seen.add(y)
                    nf.append(y)
        fr = nf
    assert len(seen) == N, "not onto"
    bad = 0
    for h in gens:
        a = ph[h]
        ma = mult[a]
        for x in range(N):
            mx = mult[x]
            mxa = mult[mx[a]]
            for y in range(N):
                if mxa[y] != mx[ma[y]]:
                    bad += 1
    print(f"  1. identity, commutativity, associativity (Light's test over {len(gens)} generators): "
          f"{'OK' if not bad else 'FAIL %d' % bad}  ({time.time() - t0:.1f}s)")
    assert not bad

    # 2. onto
    seen = {0}
    fr = [0]
    while fr:
        nf = []
        for q in fr:
            for h in gens:
                y = mult[q][ph[h]]
                if y not in seen:
                    seen.add(y)
                    nf.append(y)
        fr = nf
    onto = len(seen) == N
    print(f"  2. Phi onto (generated submonoid has {len(seen)} of {N} elements): {onto}")
    assert onto

    # 3. reduced: coarsest partition refining P that is stable under multiplication by generators
    cls = [int(p) for p in P]
    k = len(set(cls))
    while True:
        sig = {}
        new = []
        for x in range(N):
            key = (cls[x],) + tuple(cls[mult[x][ph[h]]] for h in gens)
            new.append(sig.setdefault(key, len(sig)))
        if len(sig) == k:
            break
        cls, k = new, len(sig)
    # since Q is generated by the Phi(h), stability under generators = congruence, and
    # x ~ y iff P[xz] == P[yz] for all z in Q.
    print(f"  3. reduced: indistinguishability classes = {k} (need {N}): {k == N}")
    assert k == N

    # 4.
    print(f"  4. P[identity] = {P[0]} (must be False): {not P[0]}")
    assert not P[0]

    # option images of each strip
    def img(parts):
        x = 0
        for p in parts:
            x = mult[x][ph[p]]
        return x

    O = {h: sorted({img(t) for t in strip_options(h)}) for h in gens}
    Omask = {h: sum(1 << o for o in O[h]) for h in gens}

    # 5. P-condition
    pfail = []
    for y in range(N):
        for h in gens:
            if P[mult[y][ph[h]]] and any(P[mult[y][o]] for o in O[h]):
                pfail.append((y, h))
    print(f"  5. P-condition failures: {len(pfail)} {pfail[:5]}")
    assert not pfail

    # 6. N-condition by antichain fixpoint
    Pmask = sum(1 << i for i in range(N) if P[i])
    cache = {}

    def times(E, g):
        key = (E, g)
        r = cache.get(key)
        if r is not None:
            return r
        r = 0
        e = E
        while e:
            low = e & -e
            i = low.bit_length() - 1
            r |= 1 << mult[i][g]
            e ^= low
        if len(cache) < 3_000_000:
            cache[key] = r
        return r

    anti = {}          # x -> list of minimal E (bitmasks)
    work = []
    nfail = []
    inserted = 0

    def insert(x, E):
        nonlocal inserted
        lst = anti.setdefault(x, [])
        for D in lst:
            if D & ~E == 0:
                return False
        lst[:] = [D for D in lst if E & ~D != 0]
        lst.append(E)
        inserted += 1
        if not P[x] and (E & Pmask) == 0:
            nfail.append((x, E))
        work.append((x, E))
        return True

    for h in gens:                     # positions consisting of a single strip
        insert(ph[h], Omask[h])
    steps = 0
    while work:
        x, E = work.pop()
        # skip if this pair has since been removed (dominated by a smaller one, processed instead)
        if E not in anti.get(x, ()):
            continue
        for h in gens:
            g = ph[h]
            x2 = mult[x][g]
            E2 = times(E, g)
            xm = mult[x]
            for o in O[h]:
                E2 |= 1 << xm[o]
            insert(x2, E2)
        steps += 1
        if steps % 20000 == 0:
            print(f"     ... processed {steps}, inserted {inserted}, pending {len(work)}, "
                  f"antichain {sum(len(v) for v in anti.values())}  ({time.time() - t0:.0f}s)", flush=True)
    total = sum(len(v) for v in anti.values())
    print(f"  6. N-condition: antichain fixpoint processed {steps} pairs ({inserted} insertions), final "
          f"antichain {total} pairs over {len(anti)} elements; failures: {len(nfail)}"
          f"  ({time.time() - t0:.1f}s)")
    assert not nfail
    # every element of Q should occur as Phi of some nonempty position
    print(f"     elements realised by nonempty positions: {len(anti)} of {N}")
    print(f"RESULT: (Q, P, Phi) is the misere quotient of all sums of strips of length <= {H}: "
          f"order {N}, P-portion {sum(P)}")
    single = [h for h in range(1, H + 1) if P[ph[h]]]
    print(f"single strips h <= {H} with Phi(h) in P: {single}")
    print(f"strips with Phi = identity: {[h for h in range(1, H + 1) if ph[h] == 0]}")


if __name__ == "__main__":
    main(sys.argv[1])
