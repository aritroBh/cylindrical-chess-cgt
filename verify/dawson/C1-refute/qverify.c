/* Independent verifier for a candidate misere quotient of octal 0.137 (Dawson's chess strips).
 *
 * Written from scratch for the C1-refute check; shares no code with dawson/quotient.py.
 *
 * Certificate: commutative monoid Q (mult table), subset P, map phi: strip length -> Q for
 * strips 0..nmax (phi(0) = identity).  A position is a finite multiset of strips of length
 * 1..nmax; Phi(position) = product of phi.  Claim to prove: for every position G,
 *     G is a misere P-position  <=>  Phi(G) in P,
 * and Q is reduced, phi generates Q.  Then Q is the misere quotient, so |Q| and |P| are the
 * order and P-portion.
 *
 * Move rule of 0.137 strips, derived from the pawn picture: a move picks a file f in 1..n,
 * removes f and its (existing) neighbours, leaving strips max(0,f-2) and max(0,n-f-1).
 *
 * Proof obligations checked here (induction on the game tree):
 *   (0) identity not in P (empty position: no move, a misere N-position).
 *   (P) for every y in Q, every strip n, if y*phi(n) in P then for every option o of n,
 *       y*phi(o) not in P.  (Every y is realised since phi generates Q, but sufficiency
 *       does not even need that.)
 *   (N) for every nonempty position G with Phi(G) not in P there is a strip h in G and an
 *       option o of h with Phi(G-h)*phi(o) in P.  Checked EXACTLY by a dynamic programme over
 *       strip lengths 1..nmax (see ncheck()), searching for a counterexample.
 * Plus: mult closed, identity, commutative, associative (all N^3 triples), phi onto, reduced.
 *
 * Usage: qverify cert.txt [maxlen]   (maxlen < nmax restricts to strips <= maxlen)
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

#define MAXN 2048
#define W ((MAXN + 63) / 64)

static int N, NW;
static int *M;            /* M[a*N+b] */
static unsigned char *P;
static int nmax, phi[256];
static int ident = -1;

typedef struct { uint64_t w[W]; } bs;

static inline int mul(int a, int b) { return M[a * N + b]; }
static inline int bget(const bs *s, int i) { return (s->w[i >> 6] >> (i & 63)) & 1; }
static inline void bset(bs *s, int i) { s->w[i >> 6] |= (uint64_t)1 << (i & 63); }
static inline void bclr(bs *s) { memset(s->w, 0, sizeof(uint64_t) * NW); }
static inline int bsubset(const bs *a, const bs *b) { /* a subset of b */
    for (int k = 0; k < NW; k++) if (a->w[k] & ~b->w[k]) return 0;
    return 1;
}
static inline int bequal(const bs *a, const bs *b) {
    for (int k = 0; k < NW; k++) if (a->w[k] != b->w[k]) return 0;
    return 1;
}
static inline void bor(bs *a, const bs *b) { for (int k = 0; k < NW; k++) a->w[k] |= b->w[k]; }
/* out = {b : a*b in S} */
static void pre(int a, const bs *S, bs *out) {
    bs r; bclr(&r);
    const int *row = M + a * N;
    for (int b = 0; b < N; b++) if (bget(S, row[b])) bset(&r, b);
    *out = r;
}
static int bcount(const bs *s) { int c = 0; for (int k = 0; k < NW; k++) c += __builtin_popcountll(s->w[k]); return c; }

/* options of strip n: nopt pairs (L,R) */
static int options(int n, int *L, int *R) {
    int k = 0;
    for (int f = 1; f <= n; f++) {
        int l = f - 2; if (l < 0) l = 0;
        int r = n - f - 1; if (r < 0) r = 0;
        L[k] = l; R[k] = r; k++;
    }
    return k;
}

static void die(const char *msg) { printf("FAIL: %s\n", msg); exit(1); }
static int keep = 0, nfail = 0; static char failed[512] = "";
static void soft(const char *msg) { printf("FAIL: %s\n", msg); if (!keep) exit(1); nfail++; strncat(failed, msg, 400 - strlen(failed)); strncat(failed, "; ", 2); }

/* ---------------- N-check dynamic programme ----------------
 * Process strip lengths n = 1..maxlen in order.  A partial state after lengths 1..k is
 *   x = Phi(prefix) ,  F = set of b in Q such that, if the strips of lengths > k multiply to b,
 *                         some already-chosen strip type i has Phi(G - h_i) in W_i,
 * where W_i = {y : exists option o of strip i with y*phi(o) in P} ("residual that lets the
 * mover win by moving in a strip i").  G is an N-counterexample iff G nonempty, Phi(G) not in
 * P, and for every type i present, Phi(G-h_i) not in W_i, i.e. at the end (b = identity)
 * identity not in F.  Choosing c copies of type n with g = phi(n):
 *   x' = x*g^c,   F' = {b : g^c b in F}  U  (c>=1 ? {b : x g^(c-1) b in W_n} : {}).
 * Only (g^c, g^(c-1)) matters, so c ranges over 0..m+p (m = index, p = period of g).
 * Smaller F is always at least as good for a counterexample (all maps are monotone), so per
 * x only the inclusion-minimal F are kept.  Pruning: let R_k = submonoid generated by the
 * phi of lengths > k; a state can only finish if some r in R_k has r not in F and x*r not
 * in P (necessary condition), otherwise it is dropped.
 */
typedef struct { int x; bs F; unsigned char cnt[64]; } state;
typedef struct { state *a; int n, cap; } vec;
static void vpush(vec *v, const state *s) {
    if (v->n == v->cap) { v->cap = v->cap ? 2 * v->cap : 8; v->a = realloc(v->a, sizeof(state) * v->cap); }
    v->a[v->n++] = *s;
}

static long long inserted, dominated;
/* insert into per-x antichain */
static void insert(vec *tab, const state *s) {
    vec *v = &tab[s->x];
    for (int i = 0; i < v->n; i++) if (bsubset(&v->a[i].F, &s->F)) { dominated++; return; }
    int j = 0;
    for (int i = 0; i < v->n; i++) if (!bsubset(&s->F, &v->a[i].F)) v->a[j++] = v->a[i];
    v->n = j;
    vpush(v, s);
    inserted++;
}

static int ncheck(int maxlen) {
    int L[256], R[256];
    /* W_n as bitsets, and preW[n][a] = {b : a b in W_n} */
    bs *Wn = calloc(maxlen + 1, sizeof(bs));
    for (int n = 1; n <= maxlen; n++) {
        int k = options(n, L, R);
        bclr(&Wn[n]);
        for (int y = 0; y < N; y++)
            for (int i = 0; i < k; i++)
                if (P[mul(y, mul(phi[L[i]], phi[R[i]]))]) { bset(&Wn[n], y); break; }
    }
    bs *preW = malloc(sizeof(bs) * (size_t)(maxlen + 1) * N);
    for (int n = 1; n <= maxlen; n++) for (int a = 0; a < N; a++) pre(a, &Wn[n], &preW[(size_t)n * N + a]);
    bs *notPpre = malloc(sizeof(bs) * N); /* {r : x r not in P} */
    bs Pset; bclr(&Pset); for (int y = 0; y < N; y++) if (P[y]) bset(&Pset, y);
    for (int x = 0; x < N; x++) {
        pre(x, &Pset, &notPpre[x]);
        for (int k = 0; k < NW; k++) notPpre[x].w[k] = ~notPpre[x].w[k];
        for (int b = N; b < NW * 64; b++) notPpre[x].w[b >> 6] &= ~((uint64_t)1 << (b & 63));
    }
    /* R_k: submonoid generated by phi(n), n > k; R_maxlen = {identity} */
    bs *Rk = malloc(sizeof(bs) * (maxlen + 1));
    {
        int *queue = malloc(sizeof(int) * N);
        for (int k = 0; k <= maxlen; k++) {
            bclr(&Rk[k]); int qh = 0, qt = 0;
            bset(&Rk[k], ident); queue[qt++] = ident;
            while (qh < qt) {
                int y = queue[qh++];
                for (int n = k + 1; n <= maxlen; n++) { int z = mul(y, phi[n]); if (!bget(&Rk[k], z)) { bset(&Rk[k], z); queue[qt++] = z; } }
            }
        }
        free(queue);
    }

    vec *cur = calloc(N, sizeof(vec));
    long long total = 0;
    for (int n = 1; n <= maxlen; n++) {
        int g = phi[n];
        /* powers of g, index m and period p */
        int pw[MAXN + 2]; int seen[MAXN]; for (int i = 0; i < N; i++) seen[i] = -1;
        pw[0] = ident; int m = -1, p = -1;
        for (int c = 0;; c++) {
            if (seen[pw[c]] >= 0) { m = seen[pw[c]]; p = c - m; break; }
            seen[pw[c]] = c; pw[c + 1] = mul(pw[c], g);
        }
        int cmax = m + p; /* c in 0..m+p ; pw[] holds 0..m+p */
        vec *nxt = calloc(N, sizeof(vec));
        inserted = dominated = 0;
        long long pruned = 0;
        /* the empty prefix (implicit state x = identity, F = {}) extended by c >= 1 copies */
        for (int c = 1; c <= cmax; c++) {
            state s; memset(&s, 0, sizeof s);
            s.x = pw[c];
            s.F = preW[(size_t)n * N + pw[c - 1]]; /* x = identity */
            s.cnt[n] = (unsigned char)c;
            bs t = Rk[n]; for (int k = 0; k < NW; k++) t.w[k] &= ~s.F.w[k] & notPpre[s.x].w[k];
            if (bcount(&t) == 0) { pruned++; continue; }
            insert(nxt, &s);
        }
        for (int x = 0; x < N; x++) {
            for (int i = 0; i < cur[x].n; i++) {
                const state *o = &cur[x].a[i];
                for (int c = 0; c <= cmax; c++) {
                    state s;
                    s.x = mul(o->x, pw[c]);
                    if (c == 0) s.F = o->F; else pre(pw[c], &o->F, &s.F);
                    if (c >= 1) bor(&s.F, &preW[(size_t)n * N + mul(o->x, pw[c - 1])]);
                    memcpy(s.cnt, o->cnt, sizeof s.cnt); s.cnt[n] = (unsigned char)c;
                    bs t = Rk[n]; for (int k = 0; k < NW; k++) t.w[k] &= ~s.F.w[k] & notPpre[s.x].w[k];
                    if (bcount(&t) == 0) { pruned++; continue; }
                    insert(nxt, &s);
                }
            }
            free(cur[x].a);
        }
        free(cur); cur = nxt;
        total = 0; for (int x = 0; x < N; x++) total += cur[x].n;
        printf("  N-check: after strip lengths <= %2d (phi=%d, index m=%d, period p=%d): %lld live states (inserted %lld, dominated %lld, pruned %lld)\n",
               n, g, m, p, total, inserted, dominated, pruned);
        fflush(stdout);
    }
    /* final acceptance: rest = identity */
    int found = 0;
    for (int x = 0; x < N && !found; x++) {
        if (P[x]) continue;
        for (int i = 0; i < cur[x].n; i++) {
            if (!bget(&cur[x].a[i].F, ident)) {
                printf("N-COUNTEREXAMPLE: Phi=%d not in P, no P-option; strip counts (reduced):", x);
                for (int n = 1; n <= maxlen; n++) if (cur[x].a[i].cnt[n]) printf(" %d^%d", n, cur[x].a[i].cnt[n]);
                printf("\n");
                found = 1; break;
            }
        }
    }
    return !found;
}

int main(int argc, char **argv) {
    if (argc < 2) { fprintf(stderr, "usage: %s cert.txt [maxlen]\n", argv[0]); return 2; }
    FILE *f = fopen(argv[1], "r"); if (!f) { perror("open"); return 2; }
    if (fscanf(f, "%d", &N) != 1 || N < 1 || N > MAXN) die("bad N");
    NW = (N + 63) / 64;
    M = malloc(sizeof(int) * N * N); P = malloc(N);
    for (int i = 0; i < N * N; i++) { if (fscanf(f, "%d", &M[i]) != 1) die("short mult"); if (M[i] < 0 || M[i] >= N) die("mult out of range"); }
    for (int i = 0; i < N; i++) { int b; if (fscanf(f, "%d", &b) != 1) die("short P"); P[i] = (unsigned char)(b != 0); }
    if (fscanf(f, "%d", &nmax) != 1 || nmax < 1 || nmax > 200) die("bad nmax");
    for (int n = 0; n <= nmax; n++) { if (fscanf(f, "%d", &phi[n]) != 1) die("short phi"); if (phi[n] < 0 || phi[n] >= N) die("phi out of range"); }
    fclose(f);
    int maxlen = nmax; if (argc >= 3) maxlen = atoi(argv[2]);
    if (getenv("QV_KEEP")) keep = 1;
    if (maxlen > nmax) die("maxlen > nmax");
    if (maxlen > 63) die("maxlen > 63 unsupported");

    /* identity */
    for (int e = 0; e < N; e++) {
        int ok = 1;
        for (int x = 0; x < N && ok; x++) if (mul(e, x) != x || mul(x, e) != x) ok = 0;
        if (ok) { if (ident >= 0) die("two identities"); ident = e; }
    }
    if (ident < 0) die("no identity");
    if (phi[0] != ident) die("phi(0) != identity");
    /* commutative, associative */
    for (int a = 0; a < N; a++) for (int b = 0; b < N; b++) if (mul(a, b) != mul(b, a)) die("not commutative");
    for (int a = 0; a < N; a++) for (int b = 0; b < N; b++) { int ab = mul(a, b); for (int c = 0; c < N; c++) if (mul(ab, c) != mul(a, mul(b, c))) die("not associative"); }
    printf("monoid: N=%d, identity=%d, commutative and associative (all %lld triples)\n", N, ident, (long long)N * N * N);
    /* strip 2 identical to strip 1 */
    if (maxlen >= 2 && phi[2] != phi[1]) printf("note: phi(2) != phi(1)\n");
    /* onto */
    {
        unsigned char *seen = calloc(N, 1); int *q = malloc(sizeof(int) * N); int qh = 0, qt = 0;
        seen[ident] = 1; q[qt++] = ident;
        while (qh < qt) { int y = q[qh++]; for (int n = 1; n <= maxlen; n++) { int z = mul(y, phi[n]); if (!seen[z]) { seen[z] = 1; q[qt++] = z; } } }
        printf("phi generates %d of %d elements\n", qt, N);
        if (qt != N) soft("phi not onto");
        free(seen); free(q);
    }
    int np = 0; for (int i = 0; i < N; i++) np += P[i];
    printf("|Q| = %d, |P| = %d\n", N, np);
    if (P[ident]) soft("identity in P (empty position would be P)");
    /* P-check */
    {
        int L[256], R[256]; long long checks = 0; int pfail = 0;
        for (int n = 1; n <= maxlen && !pfail; n++) {
            int k = options(n, L, R);
            for (int y = 0; y < N && !pfail; y++) {
                if (!P[mul(y, phi[n])]) continue;
                for (int i = 0; i < k; i++) {
                    checks++;
                    if (P[mul(y, mul(phi[L[i]], phi[R[i]]))]) {
                        printf("P-FAILURE: y=%d strip %d option (%d,%d)\n", y, n, L[i], R[i]); soft("P-check"); pfail = 1; break;
                    }
                }
            }
        }
        if (!pfail) printf("P-check passed (%lld option checks)\n", checks);
    }
    /* reducedness: Moore refinement, alphabet = generators */
    {
        int *cls = malloc(sizeof(int) * N), *ncls = malloc(sizeof(int) * N);
        for (int x = 0; x < N; x++) cls[x] = P[x];
        int ncl = 0, prev = -1;
        int K = maxlen;
        int *sig = malloc(sizeof(int) * N * (K + 1));
        for (int it = 0;; it++) {
            for (int x = 0; x < N; x++) { sig[x * (K + 1)] = cls[x]; for (int n = 1; n <= K; n++) sig[x * (K + 1) + n] = cls[mul(x, phi[n])]; }
            ncl = 0;
            for (int x = 0; x < N; x++) {
                int found = -1;
                for (int y = 0; y < x; y++) if (memcmp(&sig[x * (K + 1)], &sig[y * (K + 1)], sizeof(int) * (K + 1)) == 0) { found = ncls[y]; break; }
                ncls[x] = found >= 0 ? found : ncl++;
            }
            memcpy(cls, ncls, sizeof(int) * N);
            if (ncl == prev) break;
            prev = ncl;
        }
        printf("indistinguishability classes: %d (reduced iff %d == %d)\n", ncl, ncl, N);
        if (ncl != N) soft("not reduced");
        free(cls); free(ncls); free(sig);
    }
    if (!ncheck(maxlen)) soft("N-check");
    else printf("N-check passed: every nonempty position with Phi not in P has a move to Phi in P\n");
    if (nfail) { printf("RESULT: FAIL (%s)\n", failed); return 1; }
    printf("RESULT: PASS\n");
    printf("VERIFIED: misere quotient of 0.137 strips <= %d has order %d and P-portion %d\n", maxlen, N, np);
    return 0;
}
