#!/usr/bin/env python3
"""make_wide.py: derive scan_wide.c from frontier_split1_fixed2.c: board masks become 128-bit (square = (rank-1)*16 + file) so that flat
boards of up to 10 files fit.  Nimber masks (Value, child_mask/gen results, FULL) stay 64-bit.  Nothing else changes (the output for
widths <= 8 must be byte-identical to the original; checked in wide_regress.txt)."""
import re
s = open('../star26_rings/frontier_split1_fixed2.c').read()
def rep(old, new, count=1):
    global s
    n = s.count(old)
    assert n == count, (old, n, count)
    s = s.replace(old, new)

rep('#define FULL UINT64_MAX', '#define FULL UINT64_MAX\ntypedef unsigned __int128 M;   /* board mask: square = (rank-1)*16 + file */\n'
    'static inline int ctz128(M m) { uint64_t lo = (uint64_t)m; return lo ? __builtin_ctzll(lo) : 64 + __builtin_ctzll((uint64_t)(m >> 64)); }')
rep('return (r - 1) * 8 + f; }', 'return (r - 1) * 16 + f; }')
rep('static inline uint64_t B(int f, int r) { return UINT64_C(1) << SQ(f, r); }', 'static inline M B(int f, int r) { return ((M)1) << SQ(f, r); }')
rep('return s & 7; }', 'return s & 15; }')
rep('return (s >> 3) + 1; }', 'return (s >> 4) + 1; }')
rep('static uint64_t frontW[64], frontB[64];', 'static M frontW[128], frontB[128];')
rep('static uint64_t filemask[8];', 'static M filemask[16];')
rep('uint64_t mw = 0, mb = 0;', 'M mw = 0, mb = 0;')
rep('static int ep_capturable(uint64_t ep3, uint64_t ep6,', 'static int ep_capturable(M ep3, M ep6,')
rep('uint64_t wm, uint64_t bm, uint64_t ep3, uint64_t ep6', 'M wm, M bm, M ep3, M ep6', count=s.count('uint64_t wm, uint64_t bm, uint64_t ep3, uint64_t ep6'))
s = s.replace('for (uint64_t m = wm; m; m &= m - 1)', 'for (M m = wm; m; m &= m - 1)')
s = s.replace('for (uint64_t m = bm; m; m &= m - 1)', 'for (M m = bm; m; m &= m - 1)')
s = s.replace('for (uint64_t m = mine; m && acc != FULL; m &= m - 1)', 'for (M m = mine; m && acc != FULL; m &= m - 1)')
s = s.replace('__builtin_ctzll(m)', 'ctz128(m)')
rep('uint64_t occ = wm | bm;', 'M occ = wm | bm;', count=s.count('uint64_t occ = wm | bm;'))
rep('typedef struct { uint64_t wm, bm, ep3, ep6; Value val; uint8_t used; } Entry;', 'typedef struct { M wm, bm, ep3, ep6; Value val; uint8_t used; } Entry;')
rep('static inline uint64_t mix(uint64_t x) {', 'static inline uint64_t mix(uint64_t x);\nstatic inline uint64_t mixM(M x) { return mix((uint64_t)x ^ mix((uint64_t)(x >> 64) + 0x1234567ull)); }\nstatic inline uint64_t mix(uint64_t x) {')
rep('mix(wm ^ mix(bm) ^ mix(ep3) ^ mix(ep6))', 'mix(mixM(wm) ^ mix(mixM(bm)) ^ mix(mixM(ep3)) ^ mix(mixM(ep6)))', count=2)
rep('static uint32_t component_files(uint64_t occ, int g) {', 'static uint32_t component_files(M occ, int g) {')
rep('static uint64_t clear_component_ep(uint64_t ep, uint32_t files) {', 'static M clear_component_ep(M ep, uint32_t files) {')
rep('static int has_ep_capturer(uint64_t pawns, int f, int r) {', 'static int has_ep_capturer(M pawns, int f, int r) {')
rep('uint64_t mine = white ? wm : bm, theirs = white ? bm : wm;', 'M mine = white ? wm : bm, theirs = white ? bm : wm;')
rep('uint64_t base_ep3 = clear_component_ep(ep3, epcomp);', 'M base_ep3 = clear_component_ep(ep3, epcomp);')
rep('uint64_t base_ep6 = clear_component_ep(ep6, epcomp);', 'M base_ep6 = clear_component_ep(ep6, epcomp);')
rep('uint64_t rest = mine & ~B(f, r);', 'M rest = mine & ~B(f, r);')
rep('uint64_t nm = rest | B(f, r1);', 'M nm = rest | B(f, r1);')
rep('uint64_t nm2 = rest | B(f, r2), cep3 = base_ep3, cep6 = base_ep6;', 'M nm2 = rest | B(f, r2), cep3 = base_ep3, cep6 = base_ep6;')
rep('uint64_t nm = rest | B(g, r1), nt = theirs & ~B(g, r1);', 'M nm = rest | B(g, r1), nt = theirs & ~B(g, r1);')
rep('uint64_t nm = rest | B(g, r1), nt = theirs & ~B(g, victim_r);', 'M nm = rest | B(g, r1), nt = theirs & ~B(g, victim_r);')
rep('typedef struct { uint64_t wm, bm; int n; } Root;', 'typedef struct { M wm, bm; int n; } Root;')
rep('static uint64_t transform(uint64_t m, int shift, int reflect) {\n    uint64_t out = 0;', 'static M transform(M m, int shift, int reflect) {\n    M out = 0;')
rep('static int canonical_root(uint64_t wm, uint64_t bm) {\n    uint64_t bestw = wm, bestb = bm;', 'static int canonical_root(M wm, M bm) {\n    M bestw = wm, bestb = bm;')
rep('uint64_t tw = transform(wm, shift, refl), tb = transform(bm, shift, refl);', 'M tw = transform(wm, shift, refl), tb = transform(bm, shift, refl);')
rep('static void add_root(uint64_t wm, uint64_t bm, int n) {', 'static void add_root(M wm, M bm, int n) {')
rep('        uint64_t wm = 0;\n        for (int i = 0; i < nw; i++) wm |= B(wc[iw[i]] % 8, (wc[iw[i]] / 8) + 1);', '        M wm = 0;\n        for (int i = 0; i < nw; i++) wm |= B(wc[iw[i]] % 16, (wc[iw[i]] / 16) + 1);')
rep('            uint64_t bm = 0;\n            for (int i = 0; i < nb; i++) bm |= B(bc[ib[i]] % 8, (bc[ib[i]] / 8) + 1);', '            M bm = 0;\n            for (int i = 0; i < nb; i++) bm |= B(bc[ib[i]] % 16, (bc[ib[i]] / 16) + 1);')
rep('static void pos_str(char *out, uint64_t wm, uint64_t bm) {', 'static void pos_str(char *out, M wm, M bm) {')
rep('wmax > 8', 'wmax > 10')
rep('invalid range (width 1..8,', 'invalid range (width 1..10,')
open('scan_wide.c', 'w').write('/* scan_wide.c: generated by make_wide.py from frontier_split1_fixed2.c (128-bit board masks, up to 10 files). */\n' + s)
print("ok")
